"""Stage 2: describe the NCSE data and test the selection rule.

Writes reports/01-data-inspection-tables.md with counts and samples.
The interpretation of these numbers is in reports/01-data-inspection.md
(written by hand, since it is a judgement, not a calculation).
"""

import random

import polars as pl

from .rebuild import rebuild_issue, segments
from .runlog import RunLog
from .source import load_boxes

# Words that often appear in reviews; used only to find possibly missed reviews
# among boxes that the selection rule leaves out (for the report, not for selection).
REVIEW_WORDS = r"(?i)\b(this volume|the author|the poem|the work before us|we have received|exhibition|the performance|the picture|the novel)\b"


def table(df: pl.DataFrame) -> list[str]:
    cols = df.columns
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.iter_rows():
        out.append("| " + " | ".join(f"{v:,}" if isinstance(v, int) else str(v) for v in row) + " |")
    return out + [""]


def snippet(text: str, n: int = 300) -> str:
    return " ".join(text.split())[:n].replace("|", "\\|")


def edition_overlap(boxes: pl.DataFrame, a: str, b: str, n_dates: int, rng: random.Random) -> list[str]:
    """Share of 80-character pieces of edition a's text found verbatim in edition b on the same date."""
    dates_a = set(boxes.filter(pl.col("series") == a)["issue_date"])
    dates_b = set(boxes.filter(pl.col("series") == b)["issue_date"])
    both = sorted(dates_a & dates_b)
    out = [
        f"Issue dates in {a} only: {len(dates_a - dates_b)}; in {b} only: {len(dates_b - dates_a)}; in both: {len(both)}.",
        "",
        f"| Date | share of {a} text pieces found verbatim in {b} |",
        "|---|---:|",
    ]

    def flat(series, date):
        texts = boxes.filter((pl.col("series") == series) & (pl.col("issue_date") == date))["content"]
        return " ".join(" ".join(t.split()) for t in texts)

    for date in rng.sample(both, min(n_dates, len(both))):
        ta, tb = flat(a, date), flat(b, date)
        pieces = [ta[i : i + 80] for i in range(0, max(1, len(ta) - 80), 400)]
        out.append(f"| {date} | {sum(p in tb for p in pieces) / len(pieces):.2f} |")
    return out + [""]


def run(cfg: dict) -> None:
    log = RunLog("inspect", cfg["paths"]["logs"])
    rng = random.Random(cfg["sample"]["seed"])
    rb = cfg["rebuild"]
    lines = [
        "# NCSE v2.0 data inspection: tables",
        "",
        "Generated by `uv run ncse inspect`. Do not edit by hand; see `01-data-inspection.md` for the interpretation.",
        "",
    ]
    for periodical in cfg["periodicals"]:
        allb = load_boxes(cfg, periodical, all_series=True)
        log.info(f"{periodical['name']}: {allb.height:,} boxes")
        log.count("boxes read", allb.height)
        lines += [f"## {periodical['name']}", "", "### Issue series", ""]
        lines += table(
            allb.group_by("series")
            .agg(
                issues=pl.col("issue_id").n_unique(),
                first=pl.col("issue_date").min(),
                last=pl.col("issue_date").max(),
                boxes=pl.len(),
                selected_boxes=pl.col("selected").sum(),
                used=pl.col("series").is_in(periodical["series"]).first(),
            )
            .sort("boxes", descending=True)
        )
        if periodical["file"] == "Leader":
            lines += ["### Do the two Leader editions repeat each other?", ""]
            lines += edition_overlap(allb, "LDR", "CLD", 10, rng)

        b = allb.filter(pl.col("series").is_in(periodical["series"]))
        lines += [f"### Boxes in the series used ({', '.join(periodical['series'])})", ""]
        lines += table(
            b.group_by("class")
            .agg(boxes=pl.len(), median_chars=pl.col("n_chars").median().cast(pl.Int64), max_chars=pl.col("n_chars").max())
            .sort("boxes", descending=True)
        )
        lines += ["#### Text type × box class", ""]
        lines += table(b.pivot(on="class", index="text_type", values="n_chars", aggregate_function="len").fill_null(0).sort("text_type"))
        lines += ["#### Topic labels (a box can have several or none)", ""]
        n_topics = b.select(pl.col("topics").list.len().alias("number_of_topics")).group_by("number_of_topics").len().sort("number_of_topics")
        lines += table(n_topics)
        lines += table(b.explode("topics").group_by("topics").len().sort("len", descending=True).rename({"topics": "topic", "len": "boxes"}))

        sel = b.filter("selected")
        lines += [
            "### Selection rule D-002 applied to boxes",
            "",
            f"Boxes meeting the rule: {sel.height:,} of {b.height:,} ({sel.height / b.height:.1%}); "
            f"characters: {sel['n_chars'].sum():,} of {b['n_chars'].sum():,}; issues with at least one: {sel['issue_id'].n_unique()}.",
            "",
        ]
        # Fragmentation: neighbours of selected text boxes
        b2 = b.filter(~pl.col("class").is_in(rb["exclude_classes"])).with_columns(
            prev_sel=pl.col("selected").shift(1).over("issue_id").fill_null(False),
            next_sel=pl.col("selected").shift(-1).over("issue_id").fill_null(False),
        )
        iso = b2.filter(pl.col("selected") & ~pl.col("prev_sel") & ~pl.col("next_sel")).height
        lines += [f"Selected boxes with no selected neighbour on either side (isolated): {iso:,} ({iso / max(1, sel.height):.1%}).", ""]

        # Title segments vs rebuilt articles
        n_seg, seg_pages, arts = 0, [], []
        for _, issue in b.group_by(["issue_id"], maintain_order=True):
            rows = issue.to_dicts()
            for titles, items in segments(rows):
                n_seg += 1
                seg_pages.append(len({x["page_number"] for x in titles + items}))
            arts += rebuild_issue(rows, rb["max_gap"], set(rb["exclude_classes"]))
        seg_pages.sort()
        lines += [
            "### Title segments and rebuilt articles",
            "",
            f"Title segments (a title box and everything up to the next title): {n_seg:,}; "
            f"pages per segment: median {seg_pages[len(seg_pages) // 2]}, 90th percentile {seg_pages[int(len(seg_pages) * 0.9)]}, maximum {seg_pages[-1]}.",
            "",
            f"Articles rebuilt with the D-012 rule (max_gap = {rb['max_gap']}): {len(arts):,}; "
            f"with heading: {sum(a.heading_count > 0 for a in arts):,}; only one text box: {sum(len(a.boxes) - a.heading_count == 1 for a in arts):,}; "
            f"with bridged boxes: {sum(any(n.startswith('bridged') for n in a.notes) for a in arts):,}.",
            "",
        ]

        lines += ["### Random sample of boxes meeting the rule (possible false positives)", ""]
        lines += ["| box | topics | text (first 300 characters) |", "|---|---|---|"]
        for r in sel.filter(pl.col("class") == "text").sample(10, seed=cfg["sample"]["seed"]).iter_rows(named=True):
            lines.append(f"| {r['bbox_uid']} | {', '.join(r['topics'])} | {snippet(r['content'])} |")
        lines += ["", "### Boxes not meeting the rule that use review vocabulary (possible false negatives)", ""]
        miss = b.filter(~pl.col("selected") & (pl.col("class") == "text") & pl.col("content").str.contains(REVIEW_WORDS))
        lines += [f"{miss.height:,} such boxes. Random sample:", "", "| box | text type | topics | text (first 300 characters) |", "|---|---|---|---|"]
        for r in miss.sample(min(10, miss.height), seed=cfg["sample"]["seed"]).iter_rows(named=True):
            lines.append(f"| {r['bbox_uid']} | {r['text_type']} | {', '.join(r['topics'])} | {snippet(r['content'])} |")
        lines += [""]

    out = cfg["paths"]["reports"] / "01-data-inspection-tables.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    log.info(f"written {out}")
    log.close()
